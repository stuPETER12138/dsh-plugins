#!/usr/bin/env node
/**
 * Build the browser artifact for `@local/dsh-session-share`.
 *
 * The Client module system executes only `client.js` and provides React (and
 * nothing else) to its factory, so the export engine is inlined into the same
 * factory closure instead of being a second module:
 *
 *   factory(require) {
 *     <src/export-core.js>     // defines createExportCore()
 *     const exportCore = createExportCore()
 *     <src/client-shell.js>    // defines inject + apply, registers slots
 *     return { inject, apply }
 *   }
 *
 * Usage: node tools/build-client.mjs
 */

import { readFile, writeFile, stat } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const HEADER = `/**
 * Session share — generated browser bundle of \`@local/dsh-session-share\`.
 *
 * DO NOT EDIT THIS FILE. Edit \`src/export-core.js\` or \`src/client-shell.js\`
 * and run \`node tools/build-client.mjs\`.
 */

window.__ModuleLoader__.load({
  id: '@local/dsh-session-share',
  factory: (require) => {
    const React = require('react')
    const h = React.createElement
    const { useEffect, useMemo, useRef, useState } = React

`

const FOOTER = `
    return { inject, apply }
  },
})
`

const core = await readFile(path.join(root, 'src', 'export-core.js'), 'utf8')
const shell = await readFile(path.join(root, 'src', 'client-shell.js'), 'utf8')

if (!core.includes('function createExportCore(')) {
  throw new Error('src/export-core.js must define `function createExportCore()`')
}
if (!shell.includes('const inject =') || !shell.includes('function apply(')) {
  throw new Error('src/client-shell.js must define `const inject` and `function apply(`')
}
if (shell.includes('__ModuleLoader__')) {
  throw new Error('src/client-shell.js is a factory chunk; it must not call __ModuleLoader__')
}

const bundle =
  HEADER +
  '    // ── inlined src/export-core.js ─────────────────────────────────────────\n' +
  core +
  '\n    const exportCore = createExportCore()\n\n' +
  '    // ── inlined src/client-shell.js ─────────────────────────────────────────\n' +
  shell +
  FOOTER

const target = path.join(root, 'client.js')
await writeFile(target, bundle, 'utf8')
const info = await stat(target)
console.log(`built ${path.relative(process.cwd(), target) || target} (${info.size} bytes)`)
